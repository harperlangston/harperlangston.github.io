#!/usr/bin/env python3
"""Generate the CV's publication, report and patent lists from the website.

The website (../index.html) is the single source of truth for papers and
patents. Run this after adding entries there, then rebuild the PDF:

    python3 build_lists.py && latexmk -pdf cv.tex

It writes three files that cv.tex \\input{}s:
    generated/publications.tex
    generated/reports.tex
    generated/patents.tex
"""
import html
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.join(HERE, "..", "index.html")
OUT = os.path.join(HERE, "generated")
BASE_URL = "https://harperlangston.com/"

TEX_ESCAPES = {
    "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
    "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
}
UNICODE = {
    "×": r"$\times$", "²": r"$^{2}$", "ı": r"\i{}", "−": "--", "–": "--", "—": "---",
    "’": "'", "‘": "`", "“": "``", "”": "''", "·": r"\textperiodcentered{}", "≈": r"$\approx$",
}


def tex(text):
    """Escape plain text for LaTeX."""
    out = "".join(TEX_ESCAPES.get(ch, ch) for ch in text)
    for k, v in UNICODE.items():
        out = out.replace(k, v)
    return out


def clean(fragment):
    """HTML fragment -> LaTeX, keeping <strong> as bold."""
    fragment = re.sub(r"<strong>(.*?)</strong>", "\x01\\1\x02", fragment, flags=re.S)
    text = html.unescape(re.sub(r"<[^>]+>", "", fragment))
    text = " ".join(text.split())
    text = tex(text)
    return text.replace("\x01", r"\textbf{").replace("\x02", "}")


def first(pattern, s):
    m = re.search(pattern, s, re.S)
    return m.group(1) if m else ""


def entries(section_html):
    """Yield dicts for every <article class="pub"> in a block of HTML."""
    for art in re.findall(r'<article class="pub">(.*?)</article>', section_html, re.S):
        h3 = first(r"<h3>(.*?)</h3>", art)
        title = clean(h3)
        links = re.findall(r'<a href="([^"]+)"[^>]*>([^<]+)</a>', first(r'<div class="links">(.*?)</div>', art))
        href = first(r'href="([^"]+)"', h3)
        # Prefer a DOI, then arXiv, then whatever the title links to.
        for want in ("DOI", "arXiv"):
            for url, label in links:
                if label == want:
                    href = url
                    break
            else:
                continue
            break
        if href and not href.startswith("http"):
            href = BASE_URL + href
        venue_html = first(r'<p class="venue">(.*?)</p>', art)
        award = clean(first(r'<span class="award">(.*?)</span>', venue_html))
        venue = clean(re.sub(r'<span class="award">.*?</span>', "", venue_html))
        yield dict(title=title, href=href, authors=clean(first(r'<p class="authors">(.*?)</p>', art)),
                   venue=venue.strip(), award=award)


def item(e):
    title = rf"\href{{{tex(e['href'])}}}{{{e['title']}}}" if e["href"] else e["title"]
    award = rf"\award{{{e['award']}}}" if e["award"] else ""
    return rf"\pub{{{title}}}{{{e['authors']}}}{{{e['venue']}}}{{{award}}}"


def section(s, sid):
    start = s.index(f'<section id="{sid}">')
    return s[start:s.index("</section>", start)]


def main():
    s = open(SITE, encoding="utf-8").read()
    os.makedirs(OUT, exist_ok=True)
    header = "% Generated by build_lists.py from ../index.html -- edit the website, not this file.\n"

    # Publications, grouped by the year headings on the site.
    pubs = section(s, "publications")
    lines = [header]
    parts = re.split(r'<h3 class="year">(.*?)</h3>', pubs)
    for i in range(1, len(parts), 2):
        lines.append(rf"\yearhead{{{tex(parts[i])}}}")
        lines += [item(e) for e in entries(parts[i + 1])]
    open(os.path.join(OUT, "publications.tex"), "w", encoding="utf-8").write("\n".join(lines) + "\n")

    reps = [header] + [item(e) for e in entries(section(s, "reports"))]
    open(os.path.join(OUT, "reports.tex"), "w", encoding="utf-8").write("\n".join(reps) + "\n")

    pats = section(s, "patents")
    lines = [header]
    parts = re.split(r'<h3 class="year">(.*?)</h3>', pats)
    for i in range(1, len(parts), 2):
        label = re.sub(r"\s*·\s*\d+$", "", html.unescape(parts[i]))
        lines.append(rf"\subhead{{{tex(label)}}}")
        lines += [item(e) for e in entries(parts[i + 1])]
    open(os.path.join(OUT, "patents.tex"), "w", encoding="utf-8").write("\n".join(lines) + "\n")

    n = lambda t: t.count(r"\pub{")
    print(f"publications: {n(open(os.path.join(OUT, 'publications.tex')).read())}, "
          f"reports: {len(reps) - 1}, patents: {n(open(os.path.join(OUT, 'patents.tex')).read())}")


if __name__ == "__main__":
    main()
